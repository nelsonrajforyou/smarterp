-- 12. TIMETABLE MANAGEMENT


CREATE TABLE ROOMS (
    ROOM_ID VARCHAR(36) PRIMARY KEY,
    ROOM_NAME VARCHAR(100) NOT NULL, 
    ROOM_TYPE VARCHAR(50) NOT NULL, 
    CAPACITY INT NOT NULL,
    IS_ACTIVE INT DEFAULT 1,
    IS_DELETED INT DEFAULT 0
);

CREATE TABLE TIMETABLE_CONFIG (
    CONFIG_ID VARCHAR(36) PRIMARY KEY,
    ACADEMIC_YEAR_ID VARCHAR(36) NOT NULL,
    DAYS_PER_WEEK INT DEFAULT 5, 
    PERIODS_PER_DAY INT DEFAULT 8,
    PERIOD_DURATION_MINS INT DEFAULT 45,
    DAY_ORDER_START_DATE DATE NULL,
    IS_ACTIVE INT DEFAULT 1,
    IS_DELETED INT DEFAULT 0,
    FOREIGN KEY (ACADEMIC_YEAR_ID) REFERENCES ACADEMIC_YEAR(ACADEMIC_YEAR_ID)
);

CREATE TABLE PERIODS (
    PERIOD_ID VARCHAR(36) PRIMARY KEY,
    CONFIG_ID VARCHAR(36) NOT NULL,
    PERIOD_NUMBER INT NOT NULL, 
    START_TIME TIME NOT NULL,
    END_TIME TIME NOT NULL,
    IS_BREAK INT DEFAULT 0, 
    LABEL VARCHAR(50), 
    IS_ACTIVE INT DEFAULT 1,
    IS_DELETED INT DEFAULT 0,
    FOREIGN KEY (CONFIG_ID) REFERENCES TIMETABLE_CONFIG(CONFIG_ID)
);



CREATE TABLE TIMETABLE_ENTRIES (
    ENTRY_ID VARCHAR(36) PRIMARY KEY,
    CLASS_ID VARCHAR(36) NOT NULL,
    PERIOD_ID VARCHAR(36) NOT NULL,
    DAY_OF_WEEK INT NOT NULL, 
    SUBJECT_ID VARCHAR(36),
    TEACHER_ID VARCHAR(36),
    ROOM_ID VARCHAR(36),
    IS_SUBSTITUTE INT DEFAULT 0,
    ORIGINAL_TEACHER_ID VARCHAR(36) NULL,
    IS_ACTIVE INT DEFAULT 1,
    IS_DELETED INT DEFAULT 0,
    FOREIGN KEY (CLASS_ID) REFERENCES CLASSES(CLASS_ID),
    FOREIGN KEY (PERIOD_ID) REFERENCES PERIODS(PERIOD_ID),
    FOREIGN KEY (SUBJECT_ID) REFERENCES subject_list(SUBJECT_ID),
    FOREIGN KEY (TEACHER_ID) REFERENCES STAFF_INFO(STAFF_ID),
    FOREIGN KEY (ROOM_ID) REFERENCES ROOMS(ROOM_ID),
    FOREIGN KEY (ORIGINAL_TEACHER_ID) REFERENCES STAFF_INFO(STAFF_ID)
);
CREATE TABLE SUP_DAY_ORDER (
    DAY_ID VARCHAR(36) not null  PRIMARY KEY,
    DAY_ORDER INT,-- 1,2,3,4,5
    DAY_ORDER_NAME VARCHAR(100), -- monday tuesday wed thurs friday
    REMARK VARCHAR(200)
);
