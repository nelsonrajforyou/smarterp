CREATE DATABASE IF NOT EXISTS SchoolErpDb;
USE SchoolErpDb;
CREATE TABLE `ACADEMIC_YEAR` (
  `ACADEMIC_YEAR_ID` varchar(36) NOT NULL,
  `ACADEMIC_YEAR` varchar(36) NOT NULL,
  `FROM_DATE` DATE NOT NULL,
  `TO_DATE` DATE NOT NULL,
  `IS_ACTIVE` INT DEFAULT '0',
  PRIMARY KEY (`ACADEMIC_YEAR_ID`)
) ;

-- 1. USER_INFO
CREATE TABLE USER_INFO (
    USER_INFO_ID VARCHAR(36) PRIMARY KEY,
    EMAIL VARCHAR(256) NOT NULL UNIQUE,
    PASSWORD_HASH VARCHAR(512) NOT NULL,
    ROLE_ID VARCHAR(36) NOT NULL,
    USER_ID VARCHAR(36) NOT NULL,
    FIRST_NAME VARCHAR(100) NOT NULL,
    LAST_NAME VARCHAR(100) NOT NULL,
    STATUS VARCHAR(50) DEFAULT 'Active',
    IS_ACTIVE INT DEFAULT 1,
    IS_DELETED INT DEFAULT 0,
    CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT DATETIME NULL
);

-- 2. ROLES
CREATE TABLE ROLES (
    ROLE_ID VARCHAR(36) PRIMARY KEY,
    NAME VARCHAR(100) NOT NULL UNIQUE,
    IS_ACTIVE INT DEFAULT 1,
    IS_DELETED INT DEFAULT 0,
    CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP
);

-- 3. USER_ROLES
CREATE TABLE USER_ROLES (
    USER_ID VARCHAR(36) NOT NULL,
    ROLE_ID VARCHAR(36) NOT NULL,
    ACADEMIC_YEAR_ID varchar(36) NOT NULL,
    IS_ACTIVE int(1) default '1',
    IS_DELETED int(1) default '0',
    PRIMARY KEY (USER_ID, ROLE_ID)
);

-- 3.5. MODULES
CREATE TABLE `modules` (
  `PARENT_ID` varchar(36) NOT NULL,
  `MODULE_NAME` varchar(100) NOT NULL,
  `ICON` varchar(50) DEFAULT NULL,
  `DISPLAY_ORDER` int DEFAULT '0',
  `IS_ACTIVE` int DEFAULT '1',
  `IS_DELETED` int DEFAULT '0',
  `CREATED_AT` datetime DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`PARENT_ID`)
) ;

-- 4. MENUS
CREATE TABLE MENUS (
    MENU_ID VARCHAR(36) PRIMARY KEY,
    MENU_NAME VARCHAR(100) NOT NULL,
    MENU_URL VARCHAR(255) NOT NULL,
    ICON VARCHAR(50) NULL,
    PARENT_MENU_ID VARCHAR(36) NULL,
    DISPLAY_ORDER INT DEFAULT 0,
    IS_ACTIVE INT DEFAULT 1,
    IS_DELETED INT DEFAULT 0,
    CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (PARENT_MENU_ID) REFERENCES modules(PARENT_ID)
);

-- 5. ROLE_MENUS
CREATE TABLE ROLE_MENUS (
    ROLE_ID VARCHAR(36) NOT NULL,
    MENU_ID VARCHAR(36) NOT NULL,
    IS_ACTIVE int(1) default '1',
    IS_DELETED int(1) default '0',
    PRIMARY KEY (ROLE_ID, MENU_ID)
);

-- 6. STAFF_INFO (Formerly Teachers)
CREATE TABLE STAFF_INFO (
    STAFF_ID VARCHAR(36) PRIMARY KEY,
    NAME VARCHAR(200) NOT NULL,
    DEPARTMENT VARCHAR(100) NOT NULL,
    USER_ID VARCHAR(36) NULL,
    IS_ACTIVE INT DEFAULT 1,
    IS_DELETED INT DEFAULT 0,
    CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT DATETIME NULL
);

-- 7. CLASSES
CREATE TABLE CLASSES (
    CLASS_ID VARCHAR(36) PRIMARY KEY,
    CLASS_NAME VARCHAR(50) NOT NULL,
    SECTION VARCHAR(50) NOT NULL,
    TEACHER_ID VARCHAR(36) NULL,
    IS_ACTIVE INT DEFAULT 1,
    IS_DELETED INT DEFAULT 0,
    CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT DATETIME NULL,
    FOREIGN KEY (TEACHER_ID) REFERENCES STAFF_INFO(STAFF_ID) ON DELETE SET NULL
);

-- 8. STUDENTS_INFO
CREATE TABLE STUDENTS_INFO (
    STUDENT_ID VARCHAR(36) PRIMARY KEY,
    NAME VARCHAR(200) NOT NULL,
    MOBILE_NO VARCHAR(15) NOT NULL,
    FATHER_NAME VARCHAR(200) NOT NULL,
    MOTHER_NAME VARCHAR(200) NOT NULL,
    ADDRESS VARCHAR(255) NOT NULL,
    ADMISSION_NO VARCHAR(15) NOT NULL,
    EMAIL_ID VARCHAR(100) NOT NULL,
    GENDER_ID VARCHAR(10) NOT NULL,
    DATE_OF_BIRTH DATE NOT NULL,
    STATE_ID VARCHAR(36) NULL,
    USER_ID VARCHAR(36) NULL,
    NATIONALITY_ID VARCHAR(36) NULL,
    IS_ACTIVE INT DEFAULT 1,
    IS_DELETED INT DEFAULT 0,
    CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT DATETIME NULL
);
CREATE TABLE `STU_CLASS` (
  `STU_CLASS_ID` varchar(36) NOT NULL,
  `STUDENT_ID` varchar(36) NOT NULL,
  `CLASS_ID` varchar(36) NOT NULL,
  `ACADEMIC_YEAR_ID` varchar(36) NOT NULL,
  `REGISTER_NO` varchar(50) NOT NULL,
  `ROLL_NO` varchar(50) NOT NULL,
  `IS_LEFT` int DEFAULT '0',
  `IS_ACTIVE` int DEFAULT '1',
  `IS_DELETED` int DEFAULT '0',
  `CREATED_AT` datetime DEFAULT CURRENT_TIMESTAMP,
  `UPDATED_AT` datetime DEFAULT NULL,
  PRIMARY KEY (`STU_CLASS_ID`)
) ;
-- 9. SYSTEM_LOGS
CREATE TABLE SYSTEM_LOGS (
    LOG_ID INT AUTO_INCREMENT PRIMARY KEY,
    LOG_LEVEL VARCHAR(20) NOT NULL,
    MESSAGE TEXT NOT NULL,
    STACK_TRACE TEXT NULL,
    SOURCE VARCHAR(255) NULL,
    USER_ID VARCHAR(36) NULL,
    CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP
);

